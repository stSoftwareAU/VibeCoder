/**
 * The release contract: the operator-facing surface whose removal breaks an
 * existing host, rendered one entry per line into
 * `docs/audits/release-contract.txt`.
 *
 * `.github/scripts/next-release-tag.sh` compares that file at the last release
 * with the file at the merge being tagged:
 *
 * - a line **removed** (a config key dropped or renamed, or the callback
 *   schema version moved) is a **major** — an operator's `.config.json` or
 *   post-run hook written for the last release no longer means the same thing;
 * - a line **added** (a new config key) is a **minor** — every existing
 *   configuration still loads unchanged.
 *
 * The entries come from the code that enforces them, never a hand-kept copy:
 * the config keys are the ones `detectUnknownConfigKeys` accepts
 * (`KNOWN_CONFIG_KEYS`, plus `knownNestedConfigKeys()` for the fixed-vocabulary
 * blocks), and the callback schema is `CALLBACK_SCHEMA_VERSION`.
 * `tests/release_contract_test.ts` fails when the committed file no longer
 * matches, so a change to the surface always lands with a reviewable diff of
 * this record — and the tagger reads only the committed file, so tagging needs
 * no Deno.
 *
 * Regenerate with `deno task release-contract` (from `worker/deno/`).
 *
 * Australian English spelling used throughout (behaviour, recognised).
 */

import {
  KNOWN_CONFIG_KEYS,
  knownNestedConfigKeys,
} from "../../lib/config_unknown_keys.ts";
import { CALLBACK_SCHEMA_VERSION } from "../../lib/run_callbacks.ts";

/** The record's path, relative to the repository root. */
export const RELEASE_CONTRACT_PATH = "docs/audits/release-contract.txt";

/** `tests/support/` → repo root is four levels up. */
const REPO_ROOT = new URL("../../../../", import.meta.url);

const HEADER = [
  "# Release contract. Generated by `deno task release-contract` in",
  "# worker/deno/; do not edit by hand.",
  "#",
  "# .github/scripts/next-release-tag.sh compares this file at the last release",
  "# with the merge being tagged: a line removed is a MAJOR (a config key",
  "# dropped or renamed, or the callback schema moved), a line added is a MINOR.",
  "# Lines starting with # are ignored.",
];

/** Every contract entry, sorted, one per line. */
export function releaseContractEntries(): string[] {
  const entries = [`callback-schema ${CALLBACK_SCHEMA_VERSION}`];
  for (const key of KNOWN_CONFIG_KEYS) entries.push(`config ${key}`);
  for (const [block, keys] of knownNestedConfigKeys()) {
    for (const key of keys) entries.push(`config ${block}.${key}`);
  }
  // Byte order, so `sort` in the tagger and here agree on every line.
  return [...new Set(entries)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The file's full text: header, entries, one trailing newline. */
export function renderReleaseContract(): string {
  return [...HEADER, ...releaseContractEntries()].join("\n") + "\n";
}

/** The committed record, as it is on disk. */
export async function readCommittedReleaseContract(): Promise<string> {
  return await Deno.readTextFile(new URL(RELEASE_CONTRACT_PATH, REPO_ROOT));
}

if (import.meta.main) {
  const path = new URL(RELEASE_CONTRACT_PATH, REPO_ROOT);
  await Deno.writeTextFile(path, renderReleaseContract());
  console.log(
    `Wrote ${RELEASE_CONTRACT_PATH} (${releaseContractEntries().length} entries)`,
  );
}
