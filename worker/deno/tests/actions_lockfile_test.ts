Deno.test("parseActionsLockfile - a workflow key outside .github/workflows is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate("'.github/workflows/test.yml'", "'.github/test.yml'"),
    ),
  );
  assertStringIncludes(reason, "workflow key");
  assertStringIncludes(reason, ".github/test.yml");
});

Deno.test("parseActionsLockfile - a workflow pin without owner/repo@ref is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "        - 'actions/setup-go@v7.0.0'",
        "        - 'actions/setup-go'",
      ),
    ),
  );
  assertStringIncludes(reason, "invalid pin");
});

Deno.test("parseActionsLockfile - an unknown dependency field is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "        repo_id: 197814629",
        "        repo_id: 197814629\n        bogus: 1",
      ),
    ),
  );
  assertStringIncludes(reason, "bogus");
});

Deno.test("parseActionsLockfile - a dependency missing commit is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "        commit: 'sha1-3d3c42e5aac5ba805825da76410c181273ba90b1'\n",
        "",
      ),
    ),
  );
  assertStringIncludes(reason, "missing required field `commit`");
});

Deno.test("parseActionsLockfile - a commit digest that is not sha1/sha256 hex is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "sha1-3d3c42e5aac5ba805825da76410c181273ba90b1",
        "sha1-3d3c42e5aac5ba805825da76410c181273ba9",
      ),
    ),
  );
  assertStringIncludes(reason, "digest");
});

Deno.test("parseActionsLockfile - owner_id 0 is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "        owner_id: 44036562\n        repo_id: 197814629",
        "        owner_id: 0\n        repo_id: 197814629",
      ),
    ),
  );
  assertStringIncludes(reason, "owner_id");
});

Deno.test("parseActionsLockfile - a uses entry naming a missing dependency is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "            - 'actions/setup-go@4a3601121dd01d1626a1e23e37211e3254c1c06c'",
        "            - 'actions/setup-go@1111111111111111111111111111111111111111'",
      ),
    ),
  );
  assertStringIncludes(reason, "uses");
  assertStringIncludes(reason, "no dependency record");
});

Deno.test("parseActionsLockfile - a full-SHA key whose commit differs is invalid", () => {
  const reason = assertInvalid(
    parseActionsLockfile(
      mutate(
        "commit: 'sha1-a2bbfa25375fe432b6a289bc6b6cd05ecd0c4c32'",
        "commit: 'sha1-ffffffffffffffffffffffffffffffffffffffff'",
      ),
    ),
  );
  assertStringIncludes(reason, "commit");
  assertStringIncludes(reason, "full SHA");
});

