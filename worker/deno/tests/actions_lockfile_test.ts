// ---------------------------------------------------------------------------

Deno.test("parseActionsLockfile - the real gh-actions-lock example is valid", () => {
  const lock = assertValid(parseActionsLockfile(VALID));
  assertEquals(lock.version, "v0.0.3");
  assertEquals(
    [...lock.workflows.get(".github/workflows/release.yml")!].sort(),
    ["actions/checkout@v7.0.1", "cli/gh-extension-precompile@v2.2.0"],
  );
  assert(lock.dependencies.has("actions/checkout@v7.0.1"));
  assert(
    lock.dependencies.has(
      "actions/attest-build-provenance@a2bbfa25375fe432b6a289bc6b6cd05ecd0c4c32",
    ),
  );
  assertEquals(lock.dependencies.size, 5);
});

Deno.test("parseActionsLockfile - v0.0.2 is supported", () => {
  const text = mutate("version: 'v0.0.3'", "version: 'v0.0.2'");
  assertEquals(parseActionsLockfile(text).kind, "valid");
});

Deno.test("parseActionsLockfile - hostname is allowed in v0.0.3 only", () => {
  const text = mutate(
    "        ref: 'v7.0.1'\n",
    "        ref: 'v7.0.1'\n        hostname: 'github.com'\n",
  );
  assertEquals(parseActionsLockfile(text).kind, "valid");

  const v2 = mutate("version: 'v0.0.3'", "version: 'v0.0.2'");
  const reason = assertInvalid(
    parseActionsLockfile(
      v2.replace(
        "        ref: 'v7.0.1'\n",
        "        ref: 'v7.0.1'\n        hostname: 'github.com'\n",
      ),
    ),
  );
  assertStringIncludes(reason, "hostname");
});

Deno.test("parseActionsLockfile - missing workflows and dependencies are empty", () => {
  const lock = assertValid(parseActionsLockfile("version: 'v0.0.3'\n"));
  assertEquals(lock.workflows.size, 0);
  assertEquals(lock.dependencies.size, 0);
});

Deno.test("parseActionsLockfile - a workflow pin with no dependency record is valid (stale, not invalid)", () => {
  const text = [
    "version: 'v0.0.3'",
    "workflows:",
    "    '.github/workflows/ci.yml':",
    "        - 'actions/checkout@v4'",
    "",
  ].join("\n");
  const lock = assertValid(parseActionsLockfile(text));
  assertEquals(lock.dependencies.size, 0);
  assert(
    lock.workflows.get(".github/workflows/ci.yml")!.has("actions/checkout@v4"),
  );
});

Deno.test("parseActionsLockfile - owner/repo are lower-cased, ref is kept as written", () => {
  const text = [
    "version: 'v0.0.3'",
    "workflows:",
    "    '.github/workflows/ci.yml':",
    "        - 'Actions/Checkout@V4.1'",
    "",
  ].join("\n");
  const lock = assertValid(parseActionsLockfile(text));
  assert(
    lock.workflows.get(".github/workflows/ci.yml")!.has(
      "actions/checkout@V4.1",
    ),
  );
});

