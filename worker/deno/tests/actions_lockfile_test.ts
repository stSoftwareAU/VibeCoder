const VALID = VALID_LINES.join("\n") + "\n";

/** Replace one unique substring of the valid fixture. */
function mutate(from: string, to: string): string {
  assert(VALID.includes(from), `fixture lacks ${JSON.stringify(from)}`);
  return VALID.replace(from, to);
}

function assertValid(evidence: ActionsLockfileEvidence): ValidActionsLockfile {
  assertEquals(evidence.kind, "valid");
  return evidence as ValidActionsLockfile;
}

function assertInvalid(evidence: ActionsLockfileEvidence): string {
  assertEquals(evidence.kind, "invalid");
  return (evidence as { reason: string }).reason;
}

