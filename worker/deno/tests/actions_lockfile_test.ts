const CI = ".github/workflows/ci.yml";
const wfFile = { path: CI, kind: "workflow" as const };
const lockOf = (): ValidActionsLockfile =>
  assertValid(parseActionsLockfile(VALID));

Deno.test("lockCoverage - a listed pin with a dependency record is locked", () => {
  assertEquals(
    lockCoverage(
      { path: ".github/workflows/test.yml", kind: "workflow" },
      "actions/checkout",
      "v7.0.1",
      lockOf(),
    ),
    "locked",
  );
});

Deno.test("lockCoverage - owner/repo match is case-insensitive, sub-action maps to its repo pin", () => {
  const withSub = assertValid(
    parseActionsLockfile(
      [
        "version: 'v0.0.3'",
        "workflows:",
        `    '${CI}':`,
        "        - 'github/codeql-action@v3'",
        "dependencies:",
        "    'github/codeql-action@v3':",
        "        ref: 'v3'",
        "        commit: 'sha1-1234567890abcdef1234567890abcdef12345678'",
        "        owner_id: 1",
        "        repo_id: 2",
        "",
      ].join("\n"),
    ),
  );
  assertEquals(
    lockCoverage(wfFile, "GitHub/CodeQL-Action/init", "v3", withSub),
    "locked",
  );
});

Deno.test("lockCoverage - a different ref on an onboarded workflow is stale", () => {
  assertEquals(
    lockCoverage(
      { path: ".github/workflows/test.yml", kind: "workflow" },
      "actions/checkout",
      "v5",
      lockOf(),
    ),
    "stale",
  );
});

Deno.test("lockCoverage - a listed pin with no dependency record is stale", () => {
  const onlyListed: ValidActionsLockfile = {
    kind: "valid",
    version: "v0.0.3",
    workflows: new Map([[CI, new Set(["actions/checkout@v4"])]]),
    dependencies: new Set(),
  };
  assertEquals(
    lockCoverage(wfFile, "actions/checkout", "v4", onlyListed),
    "stale",
  );
});

Deno.test("lockCoverage - an unlisted (not yet onboarded) workflow falls back to SHA-pinning", () => {
  assertEquals(
    lockCoverage(wfFile, "actions/checkout", "v7.0.1", lockOf()),
    "sha-fallback",
  );
});

Deno.test("lockCoverage - composite-action files fall back to SHA-pinning", () => {
  assertEquals(
    lockCoverage(
      { path: ".github/workflows/test.yml", kind: "composite-action" },
      "actions/checkout",
      "v7.0.1",
      lockOf(),
    ),
    "sha-fallback",
  );
});

Deno.test("lockCoverage - a reusable-workflow call falls back to SHA-pinning even when listed", () => {
  const withReusable: ValidActionsLockfile = {
    kind: "valid",
    version: "v0.0.3",
    workflows: new Map([[CI, new Set(["org/repo@v1"])]]),
    dependencies: new Set(["org/repo@v1"]),
  };
  assertEquals(
    lockCoverage(
      wfFile,
      "org/repo/.github/workflows/build.yml",
      "v1",
      withReusable,
    ),
    "sha-fallback",
  );
});

Deno.test("lockCoverage - absent and invalid lockfiles fall back to SHA-pinning", () => {
  assertEquals(
    lockCoverage(wfFile, "actions/checkout", "v4", { kind: "absent" }),
    "sha-fallback",
  );
  assertEquals(
    lockCoverage(wfFile, "actions/checkout", "v4", {
      kind: "invalid",
      reason: "x",
    }),
    "sha-fallback",
  );
});
