Deno.test("readActionsLockfile - no lockfile in the checkout is absent", async () => {
  const dir = await Deno.makeTempDir();
  try {
    assertEquals(await readActionsLockfile(dir), { kind: "absent" });
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("readActionsLockfile - a read failure other than NotFound is unreadable with the cause", async () => {
  const read = await readActionsLockfile(
    "/nonexistent-checkout",
    () =>
      Promise.reject(
        new Deno.errors.PermissionDenied("permission denied (os error 13)"),
      ),
  );
  assertEquals(read.kind, "unreadable");
  assertStringIncludes(
    (read as { reason: string }).reason,
    "permission denied (os error 13)",
  );
});

Deno.test("readActionsLockfile - a valid lockfile in the checkout is read and validated", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await Deno.mkdir(`${dir}/.github/workflows`, { recursive: true });
    await Deno.writeTextFile(`${dir}/.github/workflows/actions.lock`, VALID);
    const read = await readActionsLockfile(dir);
    assertEquals(read.kind, "valid");
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("readActionsLockfile - an invalid lockfile in the checkout is invalid", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await Deno.mkdir(`${dir}/.github/workflows`, { recursive: true });
    await Deno.writeTextFile(
      `${dir}/.github/workflows/actions.lock`,
      "version: 'v0.0.1'\n",
    );
    const read = await readActionsLockfile(dir);
    assertEquals(read.kind, "invalid");
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

