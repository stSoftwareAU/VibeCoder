/**
 * Auto-create a milestone for a planning run's sub-issues and assign them all
 * to it, when the gating rules are met. See the module docstring for the rules.
 *
 * Best-effort: an ensure or assign failure is logged and swallowed so the
 * caller's planning closure is never blocked. A per-sub-issue assign failure
 * does not abort the remaining assignments.
 */
export async function maybeCreatePlanningMilestone(
  opts: MaybeCreatePlanningMilestoneOptions,
): Promise<PlanningMilestoneOutcome> {
  const {
    repo,
    parentIssueNumber,
    parentIssueTitle,
    plannedShortTitle,
    parentMilestoneTitle,
    subIssueNumbers,
    groups,
    logger,
  } = opts;
  const gh = opts.ghCommandFn ?? runGhCommand;

  // Gate 1: the parent already owns a milestone — keep the #1300 inheritance
  // path and never create a competing milestone. Grouping does not change
  // this: a plan whose parent owns a milestone still has one owner.
  if (parentMilestoneTitle && parentMilestoneTitle.trim() !== "") {
    return {
      created: false,
      assigned: [],
      skippedReason: "parent-has-milestone",
    };
  }

  // Gate 2: a milestone only makes sense for 2+ sub-issues.
  const unique = [...new Set(subIssueNumbers)].sort((a, b) => a - b);
  if (unique.length < 2) {
    return {
      created: false,
      assigned: [],
      skippedReason: "too-few-sub-issues",
    };
  }

  // Grouped path (Issue #2175): one milestone per file-area group carrying two
  // or more sub-issues. An empty list is not a grouping — it falls through to
  // the single-milestone path below, unchanged.
  if (groups !== undefined && groups.length > 0) {
    // A sub-issue the table never named would silently keep the default branch
    // while its siblings move to a milestone branch. The gate rejects that
    // (every published sub-issue must sit in exactly one row), so reaching
    // here means the sets disagree — report it rather than lose it quietly.
    const grouped = new Set(groups.flatMap((g) => g.subIssueNumbers));
    const ungrouped = unique.filter((n) => !grouped.has(n));
    if (ungrouped.length > 0) {
      logger.warn(
        "Planning milestone groups name no group for some sub-issues — they keep the default branch (Issue #2175)",
        {
          repo,
          parentIssueNumber,
          subIssueNumbers: ungrouped.join(", "),
        },
      );
    }
    return await createGroupedPlanningMilestones({
      repo,
      parentIssueNumber,
      parentIssueTitle,
      plannedShortTitle,
      groups,
      gh,
      logger,
    });
  }

  const outcome = await ensureAndAssignGroup({
    repo,
    parentIssueNumber,
    parentIssueTitle,
    plannedShortTitle,
    subIssueNumbers: unique,
    gh,
    logger,
  });
  if (outcome.milestone === null) return { created: false, assigned: [] };

  logger.info("Auto-created planning milestone for sub-issues (Issue #2863)", {
    repo,
    parentIssueNumber,
    milestoneTitle: outcome.milestone.title,
    milestoneNumber: outcome.milestone.number,
    assignedCount: outcome.assigned.length,
  });

  return {
    created: true,
    milestoneTitle: outcome.milestone.title,
    milestoneNumber: outcome.milestone.number,
    assigned: outcome.assigned,
  };
}

/**
 * Create one milestone per file-area group and assign each group's sub-issues
 * to its own milestone (Issue #2175).
 *
 * A group of a single sub-issue gets **no** milestone — it merges straight to
 * the default branch — and is still reported, so the caller can see that the
 * skip was deliberate rather than a failure. Groups are independent: a naming,
 * ensure or assign failure in one is logged and confined to that group, and
 * every remaining group still runs. The 4-milestone cap belongs to the
 * structural gate (Issue #2172) and is deliberately not re-implemented here.
 */
async function createGroupedPlanningMilestones(opts: {
  repo: string;
  parentIssueNumber: number;
  parentIssueTitle: string;
  plannedShortTitle?: string;
  groups: readonly MilestoneGroup[];
  gh: (args: string[]) => Promise<string>;
  logger: Logger;
}): Promise<PlanningMilestoneOutcome> {
  const { repo, parentIssueNumber, groups, logger } = opts;
  const milestones: PlanningMilestoneGroupOutcome[] = [];

  for (const group of groups) {
    const subIssueNumbers = [...new Set(group.subIssueNumbers)]
      .sort((a, b) => a - b);

    // A group of one merges straight to the default branch: no milestone, and
    // the skip is recorded rather than silent.
    if (subIssueNumbers.length < 2) {
      milestones.push({
        area: group.area,
        assigned: [],
        skippedReason: "too-few-sub-issues",
      });
      continue;
    }

    const outcome = await ensureAndAssignGroup({
      repo,
      parentIssueNumber,
      parentIssueTitle: opts.parentIssueTitle,
      // The table's milestone cell is the group's own short name; the plan's
      // short title (then the parent title) is the fallback when the row
      // carries none.
      plannedShortTitle: group.title.trim() !== ""
        ? group.title
        : opts.plannedShortTitle,
      fileArea: group.area,
      subIssueNumbers,
      gh: opts.gh,
      logger,
    });

    if (outcome.milestone === null) {
      milestones.push({
        area: group.area,
        assigned: [],
        skippedReason: outcome.failure ?? "ensure-failed",
      });
      continue;
    }
    milestones.push({
      area: group.area,
      milestoneTitle: outcome.milestone.title,
      milestoneNumber: outcome.milestone.number,
      assigned: outcome.assigned,
    });
  }

  const assigned = [
    ...new Set(milestones.flatMap((m) => m.assigned)),
  ].sort((a, b) => a - b);
  const created = milestones.some((m) => m.milestoneNumber !== undefined);

  logger.info(
    "Auto-created one planning milestone per file-area group (Issue #2175)",
    {
      repo,
      parentIssueNumber,
      groupCount: groups.length,
      milestoneCount: milestones.filter((m) => m.milestoneNumber !== undefined)
        .length,
      assignedCount: assigned.length,
    },
  );

  return { created, assigned, milestones };
}

/**
 * Name, ensure and populate one milestone — the single body both paths share.
 *
 * Best-effort by contract: a naming failure (an unusable parent issue number,
 * a caller bug) and an ensure failure (a GitHub hiccup) are logged apart and
 * reported as `milestone: null`, never thrown, so planning closure is never
 * aborted. A per-sub-issue assign failure does not abort the remaining
 * assignments.
 */
async function ensureAndAssignGroup(opts: {
  repo: string;
  parentIssueNumber: number;
  parentIssueTitle: string;
  plannedShortTitle?: string;
  fileArea?: string;
  subIssueNumbers: readonly number[];
  gh: (args: string[]) => Promise<string>;
  logger: Logger;
}): Promise<{
  milestone: ResolvedMilestone | null;
  assigned: number[];
  failure?: "ensure-failed" | "naming-failed";
}> {
  const { repo, parentIssueNumber, fileArea, gh, logger } = opts;

  let title: string;
  try {
    title = buildPlanningMilestoneTitle(
      parentIssueNumber,
      opts.parentIssueTitle,
      opts.plannedShortTitle,
      fileArea,
    );
  } catch (err) {
    logger.warn("Failed to name planning milestone (non-fatal)", {
      repo,
      parentIssueNumber,
      ...(fileArea === undefined ? {} : { fileArea }),
      error: err instanceof Error ? err.message : String(err),
    });
    return { milestone: null, assigned: [], failure: "naming-failed" };
  }

  let milestone: ResolvedMilestone;
  try {
    milestone = await ensurePlanningMilestone(
      repo,
      parentIssueNumber,
      title,
      gh,
      fileArea,
    );
  } catch (err) {
    logger.warn("Failed to ensure planning milestone (non-fatal)", {
      repo,
      parentIssueNumber,
      milestoneTitle: title,
      ...(fileArea === undefined ? {} : { fileArea }),
      error: err instanceof Error ? err.message : String(err),
    });
    return { milestone: null, assigned: [], failure: "ensure-failed" };
  }

  // Assign each sub-issue to the milestone that was actually resolved — a
  // reused legacy milestone keeps its own title, so assigning by the freshly
  // generated one would silently miss it. A single failure does not abort the
  // rest.
  const assigned: number[] = [];
  for (const n of opts.subIssueNumbers) {
    try {
      await gh([
        "issue",
        "edit",
        String(n),
        "--repo",
        repo,
        "--milestone",
        milestone.title,
      ]);
      assigned.push(n);
    } catch (err) {
      logger.warn(
        "Failed to assign sub-issue to planning milestone (non-fatal)",
        {
          repo,
          subIssueNumber: n,
          milestoneTitle: milestone.title,
          milestoneNumber: milestone.number,
          error: err instanceof Error ? err.message : String(err),
        },
      );
    }
  }

  return { milestone, assigned };
}

