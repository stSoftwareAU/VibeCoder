/**
 * Ensure an open milestone for `parentIssueNumber` exists in `repo`, returning
 * the milestone GitHub holds. An existing milestone is reused **as it stands**
 * — never renamed — so milestones created before Issue #1690 (milestone #50
 * and its long quoted title) keep working and no in-flight milestone branch is
 * disturbed. Repeated calls therefore make at most one POST per
 * `(repo, parent issue)` pair.
 */
async function ensurePlanningMilestone(
  repo: string,
  parentIssueNumber: number,
  title: string,
  gh: (args: string[]) => Promise<string>,
  fileArea?: string,
): Promise<ResolvedMilestone> {
  const endpoint = `repos/${repo}/milestones`;

  const listingRaw = await gh(["api", `${endpoint}?state=open&per_page=100`]);
  const existing = findPlanningMilestone(
    listingRaw,
    parentIssueNumber,
    title,
    fileArea,
  );
  if (existing !== null) return existing;

  const createRaw = await gh([
    "api",
    "-X",
    "POST",
    endpoint,
    "-f",
    `title=${title}`,
    "-f",
    `description=${buildDescription(parentIssueNumber, fileArea)}`,
  ]);
  const created = parseMilestone(createRaw, title);
  if (created === null) {
    throw new Error(
      `ensurePlanningMilestone: malformed create response for "${title}" in ${repo}`,
    );
  }
  return created;
}

/**
 * Description embedded in newly-created planning milestones. Leads with the
 * structured {@link planningMilestoneMarker} so later runs recover the parent
 * issue from machine-readable data rather than from the title text.
 */
function buildDescription(
  parentIssueNumber: number,
  fileArea?: string,
): string {
  const area = sanitiseMilestoneTitleText(fileArea ?? "");
  const scope = area === ""
    ? `the sub-issues of issue #${parentIssueNumber}`
    : `the \`${area}\` sub-issues of issue #${parentIssueNumber}`;
  return (
    `${planningMilestoneMarker(parentIssueNumber, fileArea)} ` +
    `Auto-created by planning (Issue #2863) — groups ${scope} ` +
    `for milestone-branch delivery.`
  );
}

/**
 * Find the open milestone that belongs to `parentIssueNumber` — and, on the
 * grouped path, to `fileArea` — in order of how much the evidence can be
 * trusted:
 *
 *   1. the structured `planning-milestone` marker in the description — the
 *      authoritative match, immune to renames and truncation. The marker
 *      carries the area, so a group only ever matches its own milestone;
 *   2. an exact match on the generated title;
 *   3. a leading `#<N>` on the title — the legacy shape, which is how
 *      milestones created before Issue #1690 (e.g. #50) are still found.
 *
 * Step 3 runs on the **ungrouped path only**, and skips any milestone whose
 * description carries an `area=` marker (Issue #2175). Every group milestone
 * of one plan leads with the same `#<N>`, so without both restrictions a group
 * — or an ungrouped re-run — would adopt a sibling group's milestone and pile
 * two streams of work onto one branch.
 *
 * Returns null when the listing is malformed or nothing matches, so a fresh
 * POST can recover.
 */
function findPlanningMilestone(
  raw: string,
  parentIssueNumber: number,
  wantTitle: string,
  fileArea?: string,
): ResolvedMilestone | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (!Array.isArray(parsed)) return null;

  const entries: { milestone: ResolvedMilestone; description: string }[] = [];
  for (const entry of parsed) {
    if (entry === null || typeof entry !== "object") continue;
    const r = entry as Record<string, unknown>;
    if (typeof r.number !== "number" || typeof r.title !== "string") continue;
    entries.push({
      milestone: { number: r.number, title: r.title },
      description: typeof r.description === "string" ? r.description : "",
    });
  }

  const marker = planningMilestoneMarker(parentIssueNumber, fileArea);
  const byMarker = entries.find((e) => e.description.includes(marker));
  if (byMarker) return byMarker.milestone;

  const byTitle = entries.find((e) => e.milestone.title === wantTitle);
  if (byTitle) return byTitle.milestone;

  // Grouped lookups stop here: a group's identity is its marker or its exact
  // title, never a prefix a sibling group shares.
  if (sanitiseMilestoneTitleText(fileArea ?? "") !== "") return null;

  const byPrefix = entries.find((e) =>
    !carriesGroupedMarker(e.description) &&
    trackingIssueFromMilestoneTitle(e.milestone.title) === parentIssueNumber
  );
  return byPrefix ? byPrefix.milestone : null;
}

/**
 * Parse the single-object response from the milestone create endpoint. The
 * number is the identity and must be present; a response that omits the title
 * falls back to the title just POSTed, which is what GitHub stored.
 */
function parseMilestone(
  raw: string,
  postedTitle: string,
): ResolvedMilestone | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return null;
  }
  if (parsed === null || typeof parsed !== "object") return null;
  const r = parsed as Record<string, unknown>;
  if (typeof r.number !== "number") return null;
  return {
    number: r.number,
    title: typeof r.title === "string" && r.title !== ""
      ? r.title
      : postedTitle,
  };
}
