export interface MaybeCreatePlanningMilestoneOptions {
  /** Target repository in `owner/repo` form. */
  repo: string;
  /** Parent planning issue number — the milestone title's stable prefix. */
  parentIssueNumber: number;
  /** Parent planning issue title — bounded into the milestone title. */
  parentIssueTitle: string;
  /**
   * Explicit short name for the plan, preferred over the parent issue title
   * when the caller has one (Issue #1690). Sanitised and bounded like any
   * other title text; blank falls back to the issue title.
   */
  plannedShortTitle?: string;
  /**
   * Existing milestone title on the parent issue, if any (Issue #1300
   * inheritance). When set, this helper is a no-op.
   */
  parentMilestoneTitle?: string;
  /** Sub-issue numbers created by this planning run. */
  subIssueNumbers: number[];
  /**
   * File-area groups from the parent's `## Milestones` table, when the
   * structural gate found and accepted one (Issue #2172). Given a non-empty
   * list, the helper creates **one milestone per group** of two or more
   * sub-issues instead of one milestone for the whole plan (Issue #2175).
   * Omitted — or empty — keeps the single-milestone behaviour exactly as it
   * was. The 4-milestone cap is the gate's rule, not this helper's.
   */
  groups?: readonly MilestoneGroup[];
  /** Injectable gh runner — defaults to the production retry wrapper. */
  ghCommandFn?: (args: string[]) => Promise<string>;
  /** Logger for non-fatal warnings. */
  logger: Logger;
}

export interface PlanningMilestoneOutcome {
  /** True when a milestone was ensured and sub-issues were assigned. */
  created: boolean;
  /**
   * The title of the milestone actually used, when `created` is true. This is
   * the generated title for a new milestone, and the **existing** title when
   * one was reused — a milestone is never renamed to match (Issue #1690).
   */
  milestoneTitle?: string;
  /** The milestone number GitHub reports — the structured identity. */
  milestoneNumber?: number;
  /** Sub-issue numbers successfully assigned to the milestone. */
  assigned: number[];
  /** Reason the helper was a no-op, when `created` is false. */
  skippedReason?: "parent-has-milestone" | "too-few-sub-issues";
  /**
   * One entry per group, in the order the groups were given — present only on
   * the grouped path (Issue #2175). On that path `milestoneTitle` and
   * `milestoneNumber` above are left unset because there is no single
   * milestone to name, and `assigned` is the union across the groups.
   */
  milestones?: PlanningMilestoneGroupOutcome[];
}

/** What one file-area group produced on the grouped path (Issue #2175). */
export interface PlanningMilestoneGroupOutcome {
  /** The group's file area, as the `## Milestones` table gave it. */
  area: string;
  /** The title of the milestone used, when one was ensured. */
  milestoneTitle?: string;
  /** The milestone number GitHub reports, when one was ensured. */
  milestoneNumber?: number;
  /** Sub-issue numbers successfully assigned to this group's milestone. */
  assigned: number[];
  /**
   * Why this group produced no milestone: a group of one sub-issue merges
   * straight to the default branch, and a GitHub failure is best-effort.
   */
  skippedReason?: "too-few-sub-issues" | "ensure-failed" | "naming-failed";
}

/** A milestone resolved from the API — number and title as GitHub holds them. */
interface ResolvedMilestone {
  number: number;
  title: string;
}

