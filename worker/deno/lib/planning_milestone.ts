/**
 * Auto-milestone for planning sub-issues (Issue #2863).
 *
 * When a planning run breaks an issue into two or more sub-issues and the
 * parent issue has no milestone of its own, the worker auto-creates a GitHub
 * milestone named `#<N> <short description>` (from the parent issue) and
 * assigns every sub-issue it created to that milestone. Assigning the
 * milestone is enough to opt the sub-issues into the existing milestone-branch
 * delivery workflow (Issue #1300): their PRs auto-merge into a shared
 * `milestone/<name>` branch and the default branch is only updated via the
 * single final milestone PR.
 *
 * Gating rules (always on, no opt-out):
 *   - Parent already has a milestone → no-op (the #1300 inheritance path keeps
 *     ownership; we never create a competing milestone).
 *   - Fewer than two sub-issues → no-op (a single sub-issue is handled directly,
 *     so it gets no milestone).
 *
 * One milestone per file-area group (Issue #2175): when the caller passes the
 * `## Milestones` groups the structural gate accepted (Issue #2172), the run
 * gets **one milestone per group** of two or more sub-issues — titled
 * `#<N> <area>: <short description>` — instead of one milestone for the whole
 * plan. A group of a single sub-issue gets no milestone and merges straight to
 * the default branch. Groups are independent: each has its own marker, so
 * neither a sibling group nor a later ungrouped run can adopt another group's
 * milestone. Without groups the behaviour is exactly as it was. The
 * four-milestone cap belongs to the gate, not here.
 *
 * Naming (Issue #1690): the title is `#<N> <short description>`, generated by
 * the one shared helper {@link buildPlanningMilestoneTitle} and bounded by
 * {@link MAX_MILESTONE_TITLE_LENGTH}. The `#<N>` prefix is the stable part —
 * two parents with near-identical titles cannot collide — and the description
 * is sanitised free of quotes, newlines and control characters so the title
 * stays workable in a terminal and in `gh` search expressions. Long issue
 * titles are never copied verbatim; milestone #50 was created that way and
 * ran to `#1653 The CLI now says "hit your session limit", which …`.
 *
 * Idempotent, and compatible with milestones created before that convention:
 * an existing milestone is matched by the structured `planning-milestone`
 * marker in its description, then by exact title, then by a leading `#<N>` —
 * so a legacy long title is reused **as it stands** and never renamed. The
 * whole flow is best-effort — callers treat a failure as non-fatal so planning
 * closure is never blocked.
 *
 * Australian English spelling used throughout.
 */

import { runGhCommand } from "./github.ts";
import type { MilestoneGroup } from "./plan_milestone_groups.ts";
import { trackingIssueFromMilestoneTitle } from "./milestone_sync_streak.ts";
import type { Logger } from "../types.ts";

// ---------------------------------------------------------------------------
// Title helper — the one place a planning milestone is named (Issue #1690)
// ---------------------------------------------------------------------------

/**
 * Maximum length of a generated milestone title, in characters, including the
 * `#<N> ` prefix.
 *
 * 60 keeps the title readable in the GitHub milestone list and short enough to
 * type and search from a terminal, while still leaving enough words after the
 * `#<N> ` prefix to say what the milestone is about. (The
 * `milestone/<name>` branch slug `createMilestoneBranchName` derives is capped
 * at 50 characters of its own, so the tail of a full-length title does not
 * reach the branch name.) Milestone #50 was created from a raw issue title and
 * ran to `#1653 The CLI now says "hit your session limit", which …` — long,
 * quoted, and awkward everywhere.
 */
export const MAX_MILESTONE_TITLE_LENGTH = 60;

/**
 * Quote characters, dropped outright rather than replaced by a space, so
 * `says "hit your session limit", which` reads as
 * `says hit your session limit, which` instead of gaining stray gaps.
 */
const QUOTE_CHARS = /['"`‘’“”«»]/gu;

/**
 * Allowlist of characters a milestone title may keep: letters, digits, spaces
 * and `- _ . , :` — punctuation that needs no quoting in a shell, a `gh`
 * search expression or a branch slug. Everything else becomes a space:
 * control characters and newlines, but also the shell metacharacters
 * (`& | ; $ ( ) < >`) and glob characters that make a title awkward to type
 * or search for. An allowlist, not a denylist, so a character nobody
 * anticipated is safe by default.
 */
const UNSAFE_CHARS = /[^\p{L}\p{N} \-_.,:]/gu;

/** Trailing punctuation left dangling by a truncation, stripped from the end. */
const TRAILING_PUNCTUATION = /[\s.,:_-]+$/u;

/**
 * Reduce free text to the safe character set: quotes removed, every other
 * disallowed character replaced by a space, whitespace runs collapsed, ends
 * trimmed.
 */
function sanitiseMilestoneTitleText(text: string): string {
  return text
    .replace(QUOTE_CHARS, "")
    .replace(UNSAFE_CHARS, " ")
    .replace(/\s+/gu, " ")
    .trim();
}

/**
 * Cut `text` to at most `limit` UTF-16 units without splitting a character.
 * Iterating code points rather than slicing means an astral-plane character
 * (an emoji, a CJK extension ideograph) is either kept whole or dropped — a
 * half-character lone surrogate is not a string GitHub will accept.
 */
function cutToLength(text: string, limit: number): string {
  if (text.length <= limit) return text;
  let kept = "";
  for (const character of text) {
    if (kept.length + character.length > limit) break;
    kept += character;
  }
  return kept;
}

/**
 * Cut `text` to at most `limit` characters on a word boundary, so the title
 * ends on a whole word rather than mid-word. A boundary is only honoured when
 * it keeps at least half the budget — otherwise one very long first word would
 * collapse the title to nothing and a hard cut is used instead.
 */
function boundToWords(text: string, limit: number): string {
  if (limit <= 0) return "";
  if (text.length <= limit) return text;
  const cut = cutToLength(text, limit);
  const lastSpace = cut.lastIndexOf(" ");
  const kept = lastSpace >= Math.floor(limit / 2)
    ? cut.slice(0, lastSpace)
    : cut;
  return kept.replace(TRAILING_PUNCTUATION, "");
}

/**
 * Build the canonical planning milestone title: `#<N> <short description>`,
 * bounded by {@link MAX_MILESTONE_TITLE_LENGTH} and free of quotes, newlines
 * and control characters (Issue #1690).
 *
 * The `#<N>` prefix is the stable, unambiguous part: two parent issues with
 * near-identical titles can never collide, and the number identifies the
 * milestone even when the descriptive tail is truncated. `plannedShortTitle`
 * wins when a caller has an explicit short name for the plan; otherwise the
 * parent issue title is sanitised and bounded. A description that sanitises
 * away entirely leaves the bare `#<N>`.
 *
 * @throws Error when `parentIssueNumber` is not a positive integer — a
 *   milestone with no usable identity must fail loudly, never be named after
 *   a bad number.
 */
export function buildPlanningMilestoneTitle(
  parentIssueNumber: number,
  parentIssueTitle: string,
  plannedShortTitle?: string,
  fileArea?: string,
): string {
  if (
    !Number.isSafeInteger(parentIssueNumber) || parentIssueNumber <= 0
  ) {
    throw new Error(
      `buildPlanningMilestoneTitle: invalid parent issue number ` +
        `"${parentIssueNumber}" — must be a positive integer`,
    );
  }
  const prefix = `#${parentIssueNumber}`;
  // The head is `#<N>`, or `#<N> <area>:` when the milestone belongs to a
  // file-area group. The area is bounded to half of what the prefix leaves, so
  // a verbose area can never squeeze the description out entirely.
  const area = boundToWords(
    sanitiseMilestoneTitleText(fileArea ?? ""),
    Math.floor((MAX_MILESTONE_TITLE_LENGTH - prefix.length - 1) / 2),
  ).replace(TRAILING_PUNCTUATION, "");
  const head = area === "" ? prefix : `${prefix} ${area}:`;

  const explicit = sanitiseMilestoneTitleText(plannedShortTitle ?? "");
  const source = explicit !== ""
    ? explicit
    : sanitiseMilestoneTitleText(parentIssueTitle);
  const description = boundToWords(
    source,
    MAX_MILESTONE_TITLE_LENGTH - head.length - 1,
  );
  return description === ""
    ? head.replace(TRAILING_PUNCTUATION, "")
    : `${head} ${description}`;
}

/**
 * Structured marker embedded in the description of every planning milestone
 * the worker creates, recording the parent issue in machine-readable form.
 *
 * Lookup matches this before it looks at any title, so reuse never depends on
 * parsing human-readable text: a milestone renamed in the UI is still found,
 * and a title that had to be truncated loses nothing that identity needs.
 */
export function planningMilestoneMarker(
  parentIssueNumber: number,
  fileArea?: string,
): string {
  const area = sanitiseMilestoneTitleText(fileArea ?? "");
  const areaAttribute = area === "" ? "" : ` area="${area}"`;
  return `<!-- planning-milestone parent="${parentIssueNumber}"${areaAttribute} -->`;
}

/**
 * Whether a milestone description carries a **grouped** planning marker — one
 * with an `area=` attribute.
 *
 * The ungrouped lookup's last resort is a bare leading `#<N>`, which every
 * group's milestone for the same parent also carries. Skipping descriptions
 * that name an area is what stops the ungrouped path from adopting one of the
 * plan's group milestones (Issue #2175).
 */
function carriesGroupedMarker(description: string): boolean {
  return /<!--\s*planning-milestone\s+parent="\d+"\s+area="/u.test(
    description,
  );
}

